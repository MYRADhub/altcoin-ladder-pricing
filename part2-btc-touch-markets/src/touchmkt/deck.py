"""presentations/touch-markets/deck-data.js from results/.

    python -m touchmkt.deck
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def r(x, d=4):
    return None if x is None else round(float(x), d)


def main() -> Path:
    s = json.loads((ROOT / "results" / "summary.json").read_text())
    v = json.loads((ROOT / "results" / "kalshi_violations_exploratory.json").read_text())
    t = lambda d: {"est": r(d["est"], 5), "lo": r(d["lo"], 5), "hi": r(d["hi"], 5), "p": r(d.get("p_holm", d["p"]), 4)}
    prem = {"primary": s["primary"]} | s["sensitivity"]
    payload = {
        "events": s["events"], "trades": s["trades"], "byKind": s["by_kind_events"],
        "agreement": r(s["meta"]["resolution_agreement"], 5),
        "premium": {k: {"reach": t(x["reach premium"]), "dip": t(x["dip premium"]), "brier": t(x["Brier market minus FAIR"])} for k, x in prem.items()},
        "brier": {"market": r(s["primary"]["Brier market minus FAIR"]["market"]), "fair": r(s["primary"]["Brier market minus FAIR"]["fair"])},
        "calibration": {k: [[r(b["mean_price"], 3), r(b["win_rate"], 3)] for b in s["calibration"][k]] for k in ("p", "FAIR")},
        "mood": {k: {"slope": r(x["slope"], 5), "p": r(x["p"], 3)} for k, x in s["mood"].items() if isinstance(x, dict)},
        "trading": {"ret": r(s["trading"]["FAIR"]["return"]), "lo": r(s["trading"]["FAIR"]["lo"]), "hi": r(s["trading"]["FAIR"]["hi"])},
        "kalshi": {"pairs": s["kalshi_bound"]["pairs"], "days": s["kalshi_bound"]["days_paired"], "violations": v["violations"],
                   "violationDays": v["days"], "flat": v["within_60s_and_flat"], "executable": v["all_three"]},
    }
    co = ROOT / "results" / "crash_odds.json"
    if co.exists():
        c = json.loads(co.read_text())
        payload["crash"] = {k: {"events": v["events"], **{m: r(b) for m, b in v["brier"].items()},
                                "pMkt": r(v["tests"]["market minus history"].get("p_holm", v["tests"]["market minus history"]["p"]), 4),
                                "pOpt": r(v["tests"]["options minus history"].get("p_holm", v["tests"]["options minus history"]["p"]), 4)}
                            for k, v in [("all", c["primary_dip"]), ("daily", c["dip_by_kind"]["daily"]), ("weekly", c["dip_by_kind"]["weekly"]),
                                         ("monthly", c["dip_by_kind"]["monthly"]), ("big", c["dip_5pct_or_more_below"])]}
    # In a standalone repo where this project is a subfolder next to the viewer, decks live at the repo root.
    base = ROOT.parent if (ROOT.parent / "viewer").is_dir() and (ROOT.parent / "presentations").is_dir() else ROOT
    out = base / "presentations" / "touch-markets" / "deck-data.js"
    out.write_text("/* Generated by `python -m touchmkt.deck` from results/. Do not edit by hand. */\n"
                   f"(() => {{\nconst DeckData = {json.dumps(payload, separators=(',', ':'))};\n"
                   "if (typeof module !== 'undefined') module.exports = DeckData;\nelse globalThis.DeckData = DeckData;\n})();\n")
    return out


if __name__ == "__main__":
    print(main())
